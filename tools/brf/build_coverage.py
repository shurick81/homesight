#!/usr/bin/env python3
"""Build annual_reviews/brfs/coverage.md: one row per tracked BRF, one column per recent fiscal year, saying
for each year whether its annual report is held, extracted and verified.

Usage: build_coverage.py [--years 5]

Runs by itself after import_document.py (a report loaded) and build_index.py (values extracted or verified),
so the table always matches the repo; do not edit coverage.md by hand.

BRFs: every orgnr in annual_reviews/brfs/tracked.csv (kept by hand: the BRFs we want, also before any report
is found), plus any BRF that has reports or a profile. A broken fiscal year is shown under the year it starts.
"""
import argparse
import csv
import datetime
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
BRFS = ROOT / "annual_reviews" / "brfs"
RAW = ROOT / "raw" / "annual_reviews" / "brfs"
TRACKED = BRFS / "tracked.csv"
OUT = BRFS / "coverage.md"

VERIFIED, EXTRACTED, HELD, MISSING = "✅", "🔍", "📄", "—"


def held_years(org):
    d = RAW / org
    return {int(p.name) for p in d.glob("[0-9]*") if any(p.glob("*.pdf"))} if d.exists() else set()


def extracted_years(org):
    p = BRFS / org / "financial_events.csv"
    return {int(r["year"]) for r in csv.DictReader(p.open(encoding="utf-8"))} if p.exists() else set()


def profile(org):
    p = BRFS / org / "profile.yaml"
    return (yaml.safe_load(p.open(encoding="utf-8")) or {}) if p.exists() else {}


def build(n_years=5):
    tracked = {}
    if TRACKED.exists():
        for r in csv.DictReader(TRACKED.open(encoding="utf-8")):
            tracked[r["orgnr"]] = r
    orgs = set(tracked) | {p.name for p in RAW.glob("*-*")} | {p.parent.name for p in BRFS.glob("*/profile.yaml")}
    last = datetime.date.today().year - 1                  # the latest fiscal year whose report can exist
    years = list(range(last - n_years + 1, last + 1))

    rows = []
    for org in orgs:
        prof = profile(org)
        name = prof.get("name") or tracked.get(org, {}).get("name") or org
        kommun = prof.get("municipality") or tracked.get(org, {}).get("municipality", "")
        held, done = held_years(org), extracted_years(org)
        verified_through = int(prof.get("verified_through") or 0)
        cells = []
        for y in years:
            if y in done:
                cells.append(VERIFIED if y <= verified_through else EXTRACTED)
            elif y in held:
                cells.append(HELD)
            else:
                cells.append(MISSING)
        rows.append((kommun, name, org, cells))
    rows.sort(key=lambda r: (r[0], r[1].lower()))

    n_ok = sum(c == VERIFIED for r in rows for c in r[3])
    n_held = sum(c != MISSING for r in rows for c in r[3])
    total = len(rows) * len(years)
    lines = [
        "# Annual report coverage",
        "",
        f"Generated by `tools/brf/build_coverage.py` on {datetime.date.today().isoformat()}; do not edit.",
        f"{VERIFIED} extracted and verified · {EXTRACTED} extracted, not yet verified · "
        f"{HELD} report held, not extracted · {MISSING} no report held.",
        "Fiscal years that do not follow the calendar year are shown under the year they start.",
        "",
        f"{len(rows)} BRFs; last {len(years)} fiscal years: {n_held}/{total} reports held, "
        f"{n_ok}/{total} verified.",
        "",
        "| BRF | orgnr | kommun | " + " | ".join(map(str, years)) + " |",
        "|---|---|---|" + "|".join([":-:"] * len(years)) + "|",
    ]
    for kommun, name, org, cells in rows:
        lines.append(f"| {name} | {org} | {kommun} | " + " | ".join(cells) + " |")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return OUT, len(rows), n_held, n_ok, total


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--years", type=int, default=5)
    out, n, held, ok, total = build(ap.parse_args().years)
    print(f"{out.relative_to(ROOT)}: {n} BRFs, {held}/{total} reports held, {ok}/{total} verified")


if __name__ == "__main__":
    main()
